"""Migrations: upgrade, downgrade e sincronia com os modelos, em banco temporário."""

from __future__ import annotations

import uuid
from collections.abc import Iterator

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Engine, create_engine, inspect, text

from tests.conftest import TEST_DATABASE_URL, alembic_config, sqlalchemy_url

pytestmark = pytest.mark.integration


@pytest.fixture
def scratch_engine(migrated_engine: Engine) -> Iterator[Engine]:
    """Banco descartável criado a partir do servidor de TEST_DATABASE_URL."""
    assert TEST_DATABASE_URL
    name = f"gfb_test_mig_{uuid.uuid4().hex[:8]}"
    admin = migrated_engine.execution_options(isolation_level="AUTOCOMMIT")
    with admin.connect() as conn:
        conn.execute(text(f'CREATE DATABASE "{name}"'))
    url = sqlalchemy_url(TEST_DATABASE_URL).rsplit("/", 1)[0] + f"/{name}"
    engine = create_engine(url)
    try:
        yield engine
    finally:
        engine.dispose()
        with admin.connect() as conn:
            conn.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))


def test_upgrade_downgrade_upgrade_cycle(scratch_engine: Engine) -> None:
    with scratch_engine.begin() as conn:
        command.upgrade(alembic_config(conn), "head")
    assert {"organization", "configuration", "audit_event"} <= set(
        inspect(scratch_engine).get_table_names()
    )

    with scratch_engine.begin() as conn:
        command.downgrade(alembic_config(conn), "base")
    assert set(inspect(scratch_engine).get_table_names()) <= {"alembic_version"}

    with scratch_engine.begin() as conn:
        command.upgrade(alembic_config(conn), "head")
        revision = conn.execute(text("SELECT version_num FROM alembic_version")).scalar()
    assert revision == "0001"


def test_models_match_migrations(migrated_engine: Engine) -> None:
    with migrated_engine.connect() as conn:
        try:
            command.check(alembic_config(conn))
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - falha explicativa
            pytest.fail(f"Modelos divergem das migrations: {exc}")
